"""
Turns a trained demo model (.pt) into C tables for the ESP32 / STM32 firmware.

Writes firmware/common/model_data.h and model_data.c containing
  - the layer sizes, weights and biases of the model (32-bit floats, stored in flash)
  - the Hann window table (1024), the FFT twiddle table, and the sparse mel filter table (from librosa)
The number of mel bands is taken from the model (input size). Single-frame models only (frames = 1).

Usage (from anywhere):
    python firmware/tools/export_firmware.py --model acoustic/demo_models/fan_id_06_6dB.pt
"""
import os
import argparse
import numpy as np
import torch
import librosa

N_FFT = 1024
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'common')


def arr(name, a, ctype='float'):
    a = np.asarray(a).ravel()
    fmt = (lambda v: f'{v:.9e}f') if ctype == 'float' else (lambda v: str(int(v)))
    lines = []
    for i in range(0, len(a), 8):
        lines.append('    ' + ', '.join(fmt(v) for v in a[i:i + 8]) + ',')
    return f'const {ctype} {name}[{len(a)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', required=True)
    a = ap.parse_args()

    sd = torch.load(a.model, map_location='cpu')
    keys = sorted({k.split('.')[0] for k in sd}, key=int)
    Ws = [sd[f'{k}.weight'].numpy() for k in keys]
    Bs = [sd[f'{k}.bias'].numpy() for k in keys]
    dims = [Ws[0].shape[1]] + [w.shape[0] for w in Ws]
    mels = dims[0]
    n_params = sum(w.size + b.size for w, b in zip(Ws, Bs))

    # Hann (periodic, as librosa/scipy use), twiddles for a 1024-point FFT
    hann = 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(N_FFT) / N_FFT)
    k = np.arange(N_FFT // 2)
    tw = np.stack([np.cos(2 * np.pi * k / N_FFT), -np.sin(2 * np.pi * k / N_FFT)], 1)

    # sparse mel table
    mw = librosa.filters.mel(sr=16000, n_fft=N_FFT, n_mels=mels)       # (mels, 513)
    first, count, weights = [], [], []
    for row in mw:
        nz = np.nonzero(row)[0]
        first.append(int(nz[0]))
        count.append(int(nz[-1] - nz[0] + 1))
        weights.extend(row[nz[0]:nz[-1] + 1])

    h = f"""/* AUTO-GENERATED by firmware/tools/export_firmware.py from {os.path.basename(a.model)} - do not edit */
#ifndef MODEL_DATA_H_
#define MODEL_DATA_H_
#include <stdint.h>

#define N_FFT        {N_FFT}
#define N_BINS       {N_FFT // 2 + 1}
#define N_MELS       {mels}
#define N_LAYERS     {len(Ws)}
#define MAX_DIM      {max(dims)}
#define MODEL_PARAMS {n_params}
#define MEL_W_COUNT  {len(weights)}

extern const uint16_t LAYER_DIMS[N_LAYERS + 1];
extern const float    MODEL_W[{sum(w.size for w in Ws)}];
extern const float    MODEL_B[{sum(b.size for b in Bs)}];
extern const float    HANN[N_FFT];
extern const float    TWIDDLE[N_FFT];          /* cos,-sin interleaved, N_FFT/2 pairs */
extern const uint16_t MEL_FIRST[N_MELS];
extern const uint16_t MEL_COUNT[N_MELS];
extern const float    MEL_W[MEL_W_COUNT];
#endif
"""
    c = '/* AUTO-GENERATED - do not edit */\n#include "model_data.h"\n\n'
    c += arr('LAYER_DIMS', dims, 'uint16_t') + '\n'
    c += arr('MODEL_W', np.concatenate([w.ravel() for w in Ws])) + '\n'
    c += arr('MODEL_B', np.concatenate(Bs)) + '\n'
    c += arr('HANN', hann) + '\n' + arr('TWIDDLE', tw) + '\n'
    c += arr('MEL_FIRST', first, 'uint16_t') + '\n' + arr('MEL_COUNT', count, 'uint16_t') + '\n'
    c += arr('MEL_W', weights)
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, 'model_data.h'), 'w').write(h)
    open(os.path.join(OUT, 'model_data.c'), 'w').write(c)
    print(f'layers {dims}, {n_params} parameters ({n_params * 4 / 1024:.1f} KB float32), mel weights {len(weights)}')
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
