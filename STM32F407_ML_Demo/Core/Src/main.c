/* ---- HAL I2S DMA callbacks → forward to pdm_mic driver ------------ */
void HAL_I2S_RxHalfCpltCallback(I2S_HandleTypeDef *hi2s)
{
    if (hi2s->Instance == SPI2) pdm_mic_dma_half_cb();
}

void HAL_I2S_RxCpltCallback(I2S_HandleTypeDef *hi2s)
{
    if (hi2s->Instance == SPI2) pdm_mic_dma_full_cb();
}

/* ---- DMA IRQ handler ---- */
void DMA1_Stream3_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_i2s2_ext_rx);
}

/* ---- Fault / error handler ---- */
void Error_Handler(void)
{
    __disable_irq();
    while (1) {
        /* RED blink at ~1 Hz to signal hard fault */
        HAL_GPIO_TogglePin(LED_GPIO_PORT, LED_RED_PIN);
        for (volatile uint32_t i = 0; i < 4000000; i++);
    }
}

