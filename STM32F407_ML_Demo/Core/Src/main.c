/* ---- Clock config: 168 MHz from 8 MHz HSE (matches Discovery board) - */
static void SystemClock_Config(void)
{
    RCC_OscInitTypeDef osc = {0};
    RCC_ClkInitTypeDef clk = {0};

    __HAL_RCC_PWR_CLK_ENABLE();
    __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE1);

    osc.OscillatorType = RCC_OSCILLATORTYPE_HSE;
    osc.HSEState       = RCC_HSE_ON;
    osc.PLL.PLLState   = RCC_PLL_ON;
    osc.PLL.PLLSource  = RCC_PLLSOURCE_HSE;
    osc.PLL.PLLM       = 8;    /* HSE = 8 MHz → VCO in = 1 MHz */
    osc.PLL.PLLN       = 336;  /* VCO out = 336 MHz             */
    osc.PLL.PLLP       = RCC_PLLP_DIV2;   /* SYSCLK = 168 MHz  */
    osc.PLL.PLLQ       = 7;               /* USB = 48 MHz      */
    HAL_RCC_OscConfig(&osc);

    clk.ClockType      = RCC_CLOCKTYPE_SYSCLK | RCC_CLOCKTYPE_HCLK |
                         RCC_CLOCKTYPE_PCLK1  | RCC_CLOCKTYPE_PCLK2;
    clk.SYSCLKSource   = RCC_SYSCLKSOURCE_PLLCLK;
    clk.AHBCLKDivider  = RCC_SYSCLK_DIV1;    /* AHB  = 168 MHz */
    clk.APB1CLKDivider = RCC_HCLK_DIV4;      /* APB1 =  42 MHz */
    clk.APB2CLKDivider = RCC_HCLK_DIV2;      /* APB2 =  84 MHz */
    HAL_RCC_ClockConfig(&clk, FLASH_LATENCY_5);
}

/* ---- GPIO: LEDs already handled by led_init(); user button PA0 ---- */
static void MX_GPIO_Init(void)
{
    /* Enable clocks for all ports we touch */
    __HAL_RCC_GPIOA_CLK_ENABLE();  /* user button */
    __HAL_RCC_GPIOB_CLK_ENABLE();  /* I2S2 SCK/WS */
    __HAL_RCC_GPIOC_CLK_ENABLE();  /* I2S2 SD     */
    __HAL_RCC_GPIOD_CLK_ENABLE();  /* LEDs        */

    /* User button PA0 – input with no pull (external pull-down on board) */
    GPIO_InitTypeDef g = {0};
    g.Pin  = GPIO_PIN_0;
    g.Mode = GPIO_MODE_INPUT;
    g.Pull = GPIO_NOPULL;
    HAL_GPIO_Init(GPIOA, &g);
}

/* ---- DMA controller for I2S2 RX ---- */
static void MX_DMA_Init(void)
{
    __HAL_RCC_DMA1_CLK_ENABLE();
    /* DMA1 Stream3 Channel 0 → I2S2_ext_RX */
    HAL_NVIC_SetPriority(DMA1_Stream3_IRQn, 5, 0);
    HAL_NVIC_EnableIRQ(DMA1_Stream3_IRQn);
}

/* ---- I2S2: master receive, 16-bit PCM frame, 1.024 MHz bit clock
 *           for 64× decimation of PDM microphone at 16 kHz           ---- */
static void MX_I2S2_Init(void)
{
    /* ---- GPIO alternate functions ---- */
    GPIO_InitTypeDef g = {0};
    __HAL_RCC_GPIOB_CLK_ENABLE();
    __HAL_RCC_GPIOC_CLK_ENABLE();

    /* PB12 = I2S2_WS, PB13 = I2S2_CK */
    g.Pin       = GPIO_PIN_12 | GPIO_PIN_13;
    g.Mode      = GPIO_MODE_AF_PP;
    g.Pull      = GPIO_NOPULL;
    g.Speed     = GPIO_SPEED_FREQ_LOW;
    g.Alternate = GPIO_AF5_SPI2;
    HAL_GPIO_Init(GPIOB, &g);

    /* PC3 = I2S2ext_SD (extended I2S receive data) */
    g.Pin       = GPIO_PIN_3;
    g.Alternate = GPIO_AF6_SPI2;
    HAL_GPIO_Init(GPIOC, &g);

    /* ---- I2S peripheral ---- */
    __HAL_RCC_SPI2_CLK_ENABLE();
    hi2s2.Instance         = SPI2;
    hi2s2.Init.Mode        = I2S_MODE_MASTER_RX;
    hi2s2.Init.Standard    = I2S_STANDARD_LSB;   /* PDM uses LSB-justified */
    hi2s2.Init.DataFormat  = I2S_DATAFORMAT_16B;
    hi2s2.Init.MCLKOutput  = I2S_MCLKOUTPUT_DISABLE;
    /* AudioFreq drives the bit clock; 16000 × 64 = 1.024 MHz bit clock */
    hi2s2.Init.AudioFreq   = I2S_AUDIOFREQ_16K;
    hi2s2.Init.CPOL        = I2S_CPOL_LOW;
    hi2s2.Init.ClockSource = I2S_CLOCK_PLL;
    hi2s2.Init.FullDuplexMode = I2S_FULLDUPLEXMODE_ENABLE;  /* ext I2S */
    HAL_I2S_Init(&hi2s2);

    /* ---- DMA ---- */
    hdma_i2s2_ext_rx.Instance                 = DMA1_Stream3;
    hdma_i2s2_ext_rx.Init.Channel             = DMA_CHANNEL_0;
    hdma_i2s2_ext_rx.Init.Direction           = DMA_PERIPH_TO_MEMORY;
    hdma_i2s2_ext_rx.Init.PeriphInc           = DMA_PINC_DISABLE;
    hdma_i2s2_ext_rx.Init.MemInc              = DMA_MINC_ENABLE;
    hdma_i2s2_ext_rx.Init.PeriphDataAlignment = DMA_PDATAALIGN_HALFWORD;
    hdma_i2s2_ext_rx.Init.MemDataAlignment    = DMA_MDATAALIGN_HALFWORD;
    hdma_i2s2_ext_rx.Init.Mode                = DMA_CIRCULAR;
    hdma_i2s2_ext_rx.Init.Priority            = DMA_PRIORITY_HIGH;
    hdma_i2s2_ext_rx.Init.FIFOMode            = DMA_FIFOMODE_DISABLE;
    HAL_DMA_Init(&hdma_i2s2_ext_rx);
    __HAL_LINKDMA(&hi2s2, hdmarx, hdma_i2s2_ext_rx);
}

