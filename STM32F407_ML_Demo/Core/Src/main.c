/* main.c – STM32F407-Discovery acoustic anomaly demo
 *
 * Pipeline (Hitachi MIMII baseline, plain-C autoencoder):
 *
 *   MP45DT02 PDM mic → I2S2 DMA → PDM filter → 1024-sample PCM frame
 *   → ae_logmel()   (Hann FFT + 64 mel bands, 10·log10 dB)
 *   → Calibration   (Welford mean/std over 5 s, then alert threshold = mean+3σ)
 *   → ae_score()    (normalise → autoencoder forward pass → MSE)
 *   → LED:  GREEN = normal,  RED = anomaly
 *
 * Calibration sequence (happens once at power-on):
 *   Phase 1  ORANGE blink every frame  – collecting mean/std  (~5 s = 150 frames)
 *   Phase 2  ORANGE solid              – collecting alert threshold (~5 s)
 *   Run mode GREEN or RED every frame  – live inference
 *
 * SWV / ITM printf:
 *   Debug config → enable Serial Wire Viewer, core clock = 168 MHz.
 *   Open SWV ITM Data Console, enable port 0.
 *   OR: define MEM_TEST_UART in project symbols and wire USART2 to a USB-TTL adapter.
 *
 * Project settings reminder (all done by CubeIDE's .ioc if you use it):
 *   • MCU settings → FPv4-SP (the F407 has an FPU – use it)
 *   • Linker flags  → -lm
 *   • Optimisation  → -O2 or -O3
 *   • BSP pack      → STM32F4xx-Discovery (for pdm_filter.h/.c)
 *   • Add Core/Src and Core/Inc to include paths
 */

#include <stdio.h>
#include <string.h>
#include "main.h"
#include "ae_pipeline.h"
#include "pdm_mic.h"
#include "led.h"

/* ---- HAL handles (generated by CubeIDE .ioc) ---- */
I2S_HandleTypeDef    hi2s2;
DMA_HandleTypeDef    hdma_i2s2_ext_rx;

#ifdef MEM_TEST_UART
UART_HandleTypeDef   huart2;
int _write(int fd, char *p, int n)
{
    (void)fd;
    HAL_UART_Transmit(&huart2, (uint8_t *)p, n, 1000);
    return n;
}
#else
/* SWV ITM output */
int _write(int fd, char *p, int n)
{
    (void)fd;
    for (int i = 0; i < n; i++) ITM_SendChar((uint32_t)p[i]);
    return n;
}
#endif

/* ---- DWT cycle counter ---- */
static void cyc_init(void)
{
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL  |= DWT_CTRL_CYCCNTENA_Msk;
}
#define CYC() (DWT->CYCCNT)

/* ---- Calibration parameters ---- */
#define CAL_STAT_FRAMES   150   /* ~5 s at 32 ms / frame  → mean & std  */
#define CAL_THR_FRAMES    150   /* another 5 s             → alert level */

/* ---- Working buffers (file-scope so they don't eat stack) ---- */
static int16_t s_pcm[N_FFT];
static float   s_lm[N_MELS];

/* ---- Peripheral initialisers (mirror what CubeIDE .ioc generates) ----
 *  If you open the .ioc and regenerate code these bodies will be replaced
 *  by the generated MX_ functions – that is fine and expected.
 */
static void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_DMA_Init(void);
static void MX_I2S2_Init(void);

/* ===================================================================== */
int main(void)
{
    HAL_Init();
    SystemClock_Config();   /* 168 MHz from HSE 8 MHz PLL */

    MX_GPIO_Init();
    MX_DMA_Init();
    MX_I2S2_Init();

    led_init();
    cyc_init();

    printf("\r\n=== STM32F407 Acoustic Anomaly Demo ===\r\n");
    printf("Model: %d params (%d KB), %d mel bands\r\n",
           MODEL_PARAMS, MODEL_PARAMS * 4 / 1024, N_MELS);
    printf("Pipeline static RAM: %lu bytes\r\n",
           (unsigned long)ae_static_ram_bytes());

    /* Start microphone DMA */
    pdm_mic_init();

    /* ---- Phase 1: collect mean / std ---- */
    printf("Calibrating (phase 1 – mean/std)...\r\n");
    int cal_count = 0;
    while (cal_count < CAL_STAT_FRAMES) {
        if (!pdm_mic_frame_ready()) continue;
        pdm_mic_get_frame(s_pcm);
        ae_logmel(s_pcm, s_lm);
        ae_cal_stats_add(s_lm);
        cal_count++;
        /* blink orange to show we are calibrating */
        if (cal_count & 1) led_orange(); else led_all_off();
    }
    ae_cal_stats_done();

    /* ---- Phase 2: collect alert threshold ---- */
    printf("Calibrating (phase 2 – alert threshold)...\r\n");
    led_orange();
    cal_count = 0;
    while (cal_count < CAL_THR_FRAMES) {
        if (!pdm_mic_frame_ready()) continue;
        pdm_mic_get_frame(s_pcm);
        ae_logmel(s_pcm, s_lm);
        ae_cal_thr_add(s_lm);
        cal_count++;
    }
    ae_cal_thr_done();

    float alert = ae_alert_level();
    printf("Calibration done. Alert threshold = %.4f\r\n", alert);
    printf("Running live inference... GREEN=normal  RED=anomaly\r\n");

    /* ---- Run loop ---- */
    uint32_t frame = 0;
    while (1) {
        if (!pdm_mic_frame_ready()) continue;
        pdm_mic_get_frame(s_pcm);

        uint32_t t0 = CYC();
        ae_logmel(s_pcm, s_lm);
        uint32_t t1 = CYC();
        float score = ae_score(s_lm);
        uint32_t t2 = CYC();

        if (score > alert)
            led_red();
        else
            led_green();

        /* Print every 32 frames (~1 s) */
        if ((frame & 31) == 0) {
            float us = 1e6f / (float)SystemCoreClock;
            printf("frame %lu | feat %lu us | model %lu us | score %.4f | thr %.4f | %s\r\n",
                   (unsigned long)frame,
                   (unsigned long)((t1 - t0) * us),
                   (unsigned long)((t2 - t1) * us),
                   score, alert,
                   (score > alert) ? "ANOMALY" : "normal");
        }
        frame++;
    }
}

